// fixedSampler records the logits it was handed and returns a fixed token.
//
// It is used to inspect what a wrapper did to a row rather than what it sampled, which is the
// half of the boundary this file is about.
type fixedSampler struct {
	seen []float32
	tok  int32
}

func (f *fixedSampler) Next(logits []float32) int32 {
	f.seen = append([]float32(nil), logits...)
	return f.tok
}

// TestBiasedAddsAndDoesNotReplace pins what the bias means.
//
// OpenAI documents logit_bias as "the bias is added to the logits generated by the model prior
// to sampling", so -100 bans a token by subtracting enough to lose, not by any special case.
// A wrapper that replaced the logit instead of adding to it would pass a test that only checked
// "the banned token was not chosen" while changing every other token's probability.
func TestBiasedAddsAndDoesNotReplace(t *testing.T) {
	inner := &fixedSampler{tok: 1}
	logits := []float32{1, 2, 3}
	NewBiased([]TokenBias{{ID: 1, Bias: -100}}, inner).Next(logits)

	if len(inner.seen) != len(logits) {
		t.Fatalf("the sampler saw %d values, want %d", len(inner.seen), len(logits))
	}
	if got, want := inner.seen[1], float32(2-100); got != want {
		t.Errorf("biased logit = %v, want the sum %v", got, want)
	}
	// The neighbours have to be untouched: a wrapper that rewrote the row would change the
	// distribution the log-probability pass then describes.
	if inner.seen[0] != 1 || inner.seen[2] != 3 {
		t.Errorf("neighbouring logits changed: %v", inner.seen)
	}
}

// TestBiasedIgnoresOutOfRangeIDs covers the ids a caller can send.
//
// The bias map is keyed by token id in the request body, so an id at or past the vocabulary is
// reachable from a client. It must not panic and must not wrap around, which an unchecked
// index would do on the negative side.
func TestBiasedIgnoresOutOfRangeIDs(t *testing.T) {
	logits := []float32{1, 2}
	for _, id := range []int32{-1, 2, 1000} {
		inner := &fixedSampler{tok: 0}
		NewBiased([]TokenBias{{ID: id, Bias: -100}}, inner).Next(logits)
		if inner.seen[0] != 1 || inner.seen[1] != 2 {
			t.Errorf("bias on id %d changed the row: %v", id, inner.seen)
		}
	}
}

// TestGreedyTakesTheArgmax is the default a request gets when it names no sampler.
func TestGreedyTakesTheArgmax(t *testing.T) {
	g := Greedy()
	if got := g.Next([]float32{0.5, 3, 1}); got != 1 {
		t.Errorf("Greedy picked %d, want the argmax 1", got)
	}
	// Ties go to the lowest id, which is what a stable scan gives and what a caller comparing
	// two runs needs.
	if got := g.Next([]float32{2, 2}); got != 0 {
		t.Errorf("Greedy picked %d on a tie, want the first index", got)
	}
}

// TestNewTemperatureIsDeterministicUnderAFixedDraw pins the seam the server relies on.
//
// NewTemperature takes its uniform source as a parameter rather than reading global state, so a
// seed and a test can control it. This asserts the parameter is actually used: with a draw of 0
// the first candidate wins, and with a draw near 1 the last does.
func TestNewTemperatureIsDeterministicUnderAFixedDraw(t *testing.T) {
	logits := []float32{1, 1, 1}
	low := NewTemperature(1, 0, 0, func() float64 { return 0 })
	if got := low.Next(logits); got != 0 {
		t.Errorf("a draw of 0 picked %d, want the first candidate", got)
	}
	high := NewTemperature(1, 0, 0, func() float64 { return 0.999 })
	if got := high.Next(logits); got != 2 {
		t.Errorf("a draw near 1 picked %d, want the last candidate", got)
	}
}

// TestTokenLogprobDescribesTheWholeVocabulary is the reason the engine owns this type.
//
// The alternatives come from a log-softmax over every logit, not from a truncated candidate set:
// a caller that asked for top_logprobs wants to know how surprising the token was to the model,
// and a probability computed inside a set of one would report certainty that was never there.
//
// The chosen token's own probability has to match its entry in the list, which is the property
// the server's response relies on when it reports both.
func TestTokenLogprobDescribesTheWholeVocabulary(t *testing.T) {
	logits := []float32{0, 0, 10, 0}
	lp, alts := TokenLogprob(logits, 2, 1, 4)

	if len(alts) != 4 {
		t.Fatalf("got %d alternatives for a 4-wide vocabulary, want 4", len(alts))
	}
	if alts[0].ID != 2 {
		t.Errorf("the first alternative is token %d, want the most likely 2", alts[0].ID)
	}
	for i := 1; i < len(alts); i++ {
		if alts[i].Logprob > alts[i-1].Logprob {
			t.Errorf("alternatives are not in descending order at %d: %v > %v",
				i, alts[i].Logprob, alts[i-1].Logprob)
		}
	}
	if math.Abs(float64(alts[0].Logprob-lp)) > 1e-6 {
		t.Errorf("the chosen token's logprob %v does not match its entry %v", lp, alts[0].Logprob)
	}
	// A probability, not a raw logit: 10 against three zeros is about -0.0001, not 10.
	if lp > 0 {
		t.Errorf("logprob = %v; a log probability is never positive", lp)
	}
}

// TestTokenLogprobLowerTopReturnsFewer keeps the count the caller asked for.
func TestTokenLogprobLowerTopReturnsFewer(t *testing.T) {
	_, alts := TokenLogprob([]float32{0, 5, 1, 2}, 1, 1, 2)
	if len(alts) != 2 {
		t.Errorf("asked for 2 alternatives, got %d", len(alts))
	}
	// Zero alternatives is a real request -- completions spells "the chosen token's log
	// probability and nothing else" as logprobs: 0 -- and has to produce an empty list rather
	// than the whole vocabulary.
	_, none := TokenLogprob([]float32{0, 5, 1, 2}, 1, 1, 0)
	if len(none) != 0 {
		t.Errorf("asked for no alternatives, got %d", len(none))
	}
}

// TestNewSamplerRandIsTheSameStreamForOneSeed pins the contract that makes a seed portable.
//
// The value of a seed is that it names a stream, and that only holds if every caller builds the
// generator the same way. It did not: the server seeded PCG while `orbix run` seeded math/rand's
// older NewSource, so `--seed 42` and `seed: 42` over HTTP produced different replies for the same
// prompt. Both now come through this constructor, and the test asserts the two properties the
// constructor promises -- the same seed gives the same draws, and consecutive seeds do not.
//
// The draws are compared as a sequence rather than by a single value because a generator that
// ignored its second word would still produce a plausible first number while handing choice 0 and
// choice 1 the same stream, which is what the server does with seed+i.
func TestNewSamplerRandIsTheSameStreamForOneSeed(t *testing.T) {
	draws := func(seed int64, n int) []float64 {
		r := NewSamplerRand(seed)
		out := make([]float64, n)
		for i := range out {
			out[i] = r.Float64()
		}
		return out
	}

	a, b := draws(42, 8), draws(42, 8)
	if !slices.Equal(a, b) {
		t.Errorf("the same seed produced two streams:\n%v\n%v", a, b)
	}

	// Consecutive seeds are what the server derives for choices of one request, so they must not
	// be the same stream. This is the property a caller depends on; how the constructor spends its
	// second word is not observable through it -- replacing that word with a constant still passes,
	// measured, because PCG already separates two seeds through the first word alone. The test says
	// what it can see rather than asserting a stronger claim it cannot detect.
	c := draws(43, 8)
	if slices.Equal(a, c) {
		t.Errorf("seeds 42 and 43 produced the same stream: %v", a)
	}

	// And the stream is not the older generator's, which is the regression this pins: the reason
	// for a single constructor is that a reply is reproducible across entry points, and the entry
	// point that disagreed was the one still using NewSource.
	legacy := rand.New(rand.NewSource(42))
	legacyPrefix := make([]float64, 8)
	for i := range legacyPrefix {
		legacyPrefix[i] = legacy.Float64()
	}
	if slices.Equal(a, legacyPrefix) {
		t.Error("the generator is math/rand's NewSource stream, the one the CLI used to disagree on")
	}
}
